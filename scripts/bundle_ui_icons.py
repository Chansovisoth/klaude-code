"""Validate the pinned UI glyph registry and build its offline browser bundle."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

STATIC = Path(__file__).resolve().parents[1] / "apps/webhost/src/klaude_webhost/static"
ROOT = STATIC / "icons/ui"


def bundle(check: bool = False) -> None:
    registry = json.loads((ROOT / "registry.json").read_text())
    manifest = json.loads((ROOT / "manifest.json").read_text())
    for name, expected in manifest["assets"].items():
        if name not in {"fontawesome.json", "LICENSE.txt"}:
            raise ValueError(f"Unexpected vendor asset: {name}")
        if hashlib.sha256((ROOT / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f"Vendor asset hash mismatch: {name}")
    if manifest["source"]["version"] != registry["release"]:
        raise ValueError("Registry and vendored release differ")
    glyphs = json.loads((ROOT / "fontawesome.json").read_text())
    for name, (width, height, path) in glyphs.items():
        if not re.fullmatch(r"[a-z0-9-]+", name) or not 0 < width <= 1024 or height != 512:
            raise ValueError(f"Invalid icon canvas: {name}")
        validate_path(path)
    for name, target in registry["aliases"].items():
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*", name) or target not in glyphs:
            raise ValueError(f"Invalid UI alias: {name}")
    for name, icon in registry["custom"].items():
        if name in registry["aliases"] or not icon["reason"] or icon["viewBox"] != [0, 0, 24, 24]:
            raise ValueError(f"Invalid custom icon: {name}")
        validate_path(icon["path"])
    payload = {"glyphs": glyphs, "aliases": registry["aliases"], "custom": registry["custom"]}
    output = (
        "/* Generated by scripts/bundle_ui_icons.py. Font Awesome Free 7.2.0; "
        "icons/ui/LICENSE.txt. */\nwindow.KlaudeUIIconData = "
        + json.dumps(payload, ensure_ascii=True, separators=(",", ":"))
        + ";\n"
        + (STATIC / "ui-icons-runtime.js").read_text()
    )
    target = STATIC / "ui-icons.js"
    if check:
        assert target.read_text() == output, "Run python3 scripts/bundle_ui_icons.py"
    else:
        target.write_text(output)
    print(f"{'Verified' if check else 'Bundled'} {len(glyphs)} local Font Awesome UI icons")


def validate_path(path: str) -> None:
    if (
        not isinstance(path, str)
        or len(path) > 20000
        or not re.fullmatch(r"[MmZzLlHhVvCcSsQqTtAaEe0-9.,+\s-]+", path)
    ):
        raise ValueError("Invalid SVG path data")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    bundle(parser.parse_args().check)
