#!/usr/bin/env python3
"""Validate the data-only registry and build its offline browser/Node bundle."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATIC = ROOT / "apps/webhost/src/klaude_webhost/static"
ASSETS = STATIC / "icons/ai"


def validate_svg(content: bytes) -> None:
    if len(content) > 262144 or b"<!ENTITY" in content.upper() or b"<!DOCTYPE" in content.upper():
        raise ValueError("Oversized SVG or XML declarations")
    root = ET.fromstring(content)
    if root.tag != "{http://www.w3.org/2000/svg}svg" or "viewBox" not in root.attrib:
        raise ValueError("SVG needs an explicit viewBox")
    allowed = {
        "svg",
        "path",
        "g",
        "defs",
        "title",
        "desc",
        "circle",
        "ellipse",
        "rect",
        "polygon",
        "polyline",
        "line",
        "linearGradient",
        "radialGradient",
        "stop",
        "clipPath",
        "mask",
    }
    nodes = list(root.iter())
    if len(nodes) > 4096:
        raise ValueError("Too many SVG nodes")
    for node in nodes:
        if node.tag.rsplit("}", 1)[-1] not in allowed:
            raise ValueError(f"Forbidden SVG element: {node.tag}")
        for key, value in node.attrib.items():
            if (
                key.startswith("{")
                or key.lower().startswith("on")
                or key.lower() in {"href", "style", "class"}
            ):
                raise ValueError(f"Forbidden SVG attribute: {key}")
            if re.search(r"(?:https?:|data:|javascript:|@import|expression\s*\()", value, re.I):
                raise ValueError("External or executable SVG value")
            if "url(" in value.lower() and not re.fullmatch(r"url\(#[\w.-]+\)", value):
                raise ValueError("Only local SVG paint references are allowed")


def bundle(check: bool = False) -> None:
    registry = json.loads((ASSETS / "registry.json").read_text())
    manifest = json.loads((ASSETS / "manifest.json").read_text())
    icons = manifest["icons"]
    for name, entry in icons.items():
        if not re.fullmatch("[a-z0-9-]+", name):
            raise ValueError(f"Unsafe asset name: {name}")
        content = (ASSETS / f"{name}.svg").read_bytes()
        validate_svg(content)
        if hashlib.sha256(content).hexdigest() != entry["sha256"]:
            raise ValueError(f"Asset hash mismatch: {name}")
    provider_ids = set()
    for group in ("providers", "platforms"):
        aliases = {}
        namespaces = {}
        for record in registry[group]:
            if group == "providers":
                if record["id"] in provider_ids:
                    raise ValueError("Duplicate provider")
                provider_ids.add(record["id"])
            for alias in [record["id"], record["name"], *record["aliases"]]:
                key = re.sub(r"[\s._-]+", "", alias.lower())
                if key in aliases and aliases[key] != record["id"]:
                    raise ValueError(f"Ambiguous alias: {alias}")
                aliases[key] = record["id"]
            for namespace in record.get("namespaces", []):
                if namespace.lower() in namespaces:
                    raise ValueError(f"Duplicate publisher: {namespace}")
                namespaces[namespace.lower()] = record["id"]
    seen = set()
    for family in registry["families"]:
        if family["creator"] not in provider_ids:
            raise ValueError("Unknown family creator")
        for prefix in family["prefixes"]:
            if prefix in seen or prefix != prefix.lower():
                raise ValueError(f"Ambiguous family prefix: {prefix}")
            seen.add(prefix)
    for group in ("providers", "families", "platforms"):
        for record in registry[group]:
            if record["icon"] and record["icon"] not in icons:
                raise ValueError(f"Missing asset: {record['icon']}")
    registry["icons"] = {
        name: {"mono": name, "color": entry.get("color")} for name, entry in icons.items()
    }
    core = (ROOT / "scripts/ai_icons/resolve.js").read_text()
    output = (
        "// Generated by scripts/bundle_ai_icons.py; "
        "edit registry.json and scripts/ai_icons/resolve.js.\n"
        "(function () {\n"
        + core
        + "\nconst api = createAIIconRegistry("
        + json.dumps(registry, ensure_ascii=True, separators=(",", ":"))
        + ");\n"
        'if (typeof module === "object" && module.exports) module.exports = api;\n'
        "else globalThis.AIIcons = api;\n})();\n"
    )
    target = STATIC / "ai-icons.js"
    if check:
        if target.read_text() != output:
            raise ValueError("Stale ai-icons.js; run scripts/bundle_ai_icons.py")
    else:
        target.write_text(output)
    print(
        f"{len(registry['providers'])} creators, {len(registry['families'])} families, "
        f"{len(registry['platforms'])} platforms, {len(icons)} SVG assets validated"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    bundle(parser.parse_args().check)
